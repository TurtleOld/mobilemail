package com.mobilemail.domain.port

/**
 * Общая проверка пригодности и очистка скачанного APK. Просроченный файл не
 * считается Готовым обновлением и не передаётся установщику.
 *
 * Удаление сериализовано с использованием APK: очистка не удаляет исходный
 * файл, пока его копирует системный установщик.
 */
interface UpdateApkCleanupPort {

    /**
     * Истёк ли срок хранения скачанного APK к текущему моменту. Срок отсчитывается
     * от фактического завершения скачивания и не продлевается возвращением в
     * приложение, повтором установки или восстановлением процесса.
     */
    suspend fun isExpired(): Boolean

    /**
     * Выполняет [block] под блокировкой использования APK: параллельная очистка
     * дождётся окончания передачи файла установщику.
     */
    suspend fun <T> duringInstallTransfer(block: suspend () -> T): T

    /**
     * Удаляет только файл обновления [apkFilePath] и связанные записи загрузки
     * и установки. Почтовые данные и посторонние файлы не затрагиваются.
     */
    suspend fun clean(apkFilePath: String)
}
